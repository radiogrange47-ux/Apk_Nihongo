internal fun concisePedagogicalHint(explanation: String): String {
    val sentenceEnd = explanation.indexOfAny(charArrayOf('.', '。', '!', '?'))
    val firstSentence = if (sentenceEnd > 0) explanation.substring(0, sentenceEnd + 1) else explanation
    return if (firstSentence.length <= 110) firstSentence else firstSentence.take(107).trimEnd() + "…"
}

internal fun kanjiBreakdown(japaneseText: String): String? {
    val kanjiCharacters = japaneseText.filter { it in '\u4E00'..'\u9FFF' }.toList().distinct()
    if (kanjiCharacters.isEmpty()) return null
    val components = kanjiCharacters.map { kanji ->
        "$kanji : ${kanjiMeanings[kanji] ?: "sens à préciser"}"
    }
    return components.joinToString(" · ")
}

internal fun vocabularyKanjiBreakdown(question: VocabularyQuestion): String? =
    kanjiBreakdown(question.kanji)

internal fun phraseKanjiBreakdown(tokens: List<PhraseToken>): String? =
    kanjiBreakdown(tokens.joinToString("") { it.japanese })
